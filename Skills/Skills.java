package Skills;

public class Skills {
    public int damage;

    public float healVal;

    public int manaCost;

    public int hpCost;

    Skills(int damage, float healVal, int manaCost, int hpCost) {
        this.damage = damage;
        this.healVal = healVal;
        this.manaCost = manaCost;
        this.hpCost = hpCost;
    }
}
